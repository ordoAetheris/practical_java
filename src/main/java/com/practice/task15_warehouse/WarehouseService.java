/* ═══════════════════════ УСЛОЖНЕНИЯ (реализовать ИЗНУТРИ этого класса) ═══════════════════════
 *
 * Три НЕЗАВИСИМЫХ усложнения. Здесь — ЗАДАЧА, КОНТРАКТ и в чём ловушка. Способ решения и тесты — сам.
 *
 * ─── 1. АТОМАРНОЕ СПИСАНИЕ ОСТАТКА — защита от ухода в минус (oversell) ───
 *   Бизнес: со склада нельзя выдать больше товара, чем есть на остатке.
 *   Контракт: outgoing(productId, qty) списывает qty, только если остатка хватает; иначе отказ.
 *     Инвариант: остаток товара НИКОГДА не уходит в минус.
 *   Ловушка: наивная «проверил, что остатка хватает → списал» под несколькими потоками на один товар
 *     уводит остаток в минус — все проверили, что хватает, и все списали (lost update / TOCTOU).
 *   Проверить: остаток M, N>M потоков списывают по 1 → успешны ровно M, остаток 0, минуса нет.
 *
 * ─── 2. ИДЕМПОТЕНТНАЯ ОПЕРАЦИЯ — защита от повторного применения движения ───
 *   Бизнес: одно и то же движение (приход или расход) при повторе запроса не должно примениться дважды.
 *   Контракт: incoming/outgoing принимают opId (стабильный на одно движение); повтор с тем же opId не
 *     меняет остаток второй раз и не добавляет вторую запись в историю.
 *   Ловушка: два запроса с одним opId приходят одновременно.
 *   Проверить: outgoing(opId, 5) дважды → остаток −5, а не −10; в истории одна запись с этим opId.
 *
 * ─── 3. ПЕРЕВОД МЕЖДУ СКЛАДАМИ БЕЗ ВЗАИМНОЙ БЛОКИРОВКИ ───
 *   ⚠️ Требует расширить модель: базовая версия — ОДИН склад (остаток хранится по товару). Для этого
 *     усложнения заведи НЕСКОЛЬКО складов, у каждого свой остаток по товару (остаток по паре склад+товар).
 *   Бизнес: перевод товара со склада A на склад B должен быть атомарным (либо списалось с A и
 *     зачислилось на B, либо не произошло ничего). Встречные переводы A→B и B→A не должны вешать систему.
 *   Контракт: transfer(fromWarehouse, toWarehouse, productId, qty) — списание с A и зачисление на B как
 *     единое целое; суммарный остаток по двум складам сохраняется. Инвариант: система не зависает при
 *     встречных переводах.
 *   Ловушка: если для перевода захватывать замки двух складов в порядке «сначала from, потом to», то
 *     встречные переводы A→B и B→A возьмут их в противоположном порядке и получат взаимную блокировку
 *     (deadlock) — каждый держит один замок и ждёт второй.
 *   Проверить: множество встречных переводов A↔B не зависают; суммарный остаток двух складов неизменен.
 */
